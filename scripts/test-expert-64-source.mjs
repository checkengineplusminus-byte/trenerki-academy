#!/usr/bin/env node
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>JSON.parse(readFileSync(new URL('../'+p,import.meta.url),'utf8'));
const previous=read('content/expert-64-browser-fixture-20261117.json').lessons;
const lessons=read('content/expert-64-browser-fixture-20261117-v2.json').lessons;
const cards=read('content/testy-64-specjalistow-20261117.json').reviews;
const prev=new Map(previous.map(x=>[x.course_slug+':'+x.lesson_no,x]));
const tests=new Map(cards.map(x=>[x.slug+':'+x.lesson_no,x]));
assert.equal(lessons.length,64);assert.equal(tests.size,64);
assert.equal(new Set(cards.map(x=>x.reviewer_profile)).size,64,'Unique specialist perspectives');
assert.equal(new Set(lessons.map(x=>x.course_slug)).size,8);
for(const row of lessons){
 const key=row.course_slug+':'+row.lesson_no,old=prev.get(key),t=tests.get(key),m=row.material;
 assert(old&&t,'Missing earlier quiz or reviewed scenario '+key);
 assert.equal(m.editorial_status,'needs_expert_review','Human approval must remain pending '+key);
 assert.equal(m.editorial_revision,'2026-11-17-64-practical-v1');
 assert.equal(m.specialty_test_revision,'2026-11-17-64-specialty-test-v2');
 assert.equal(m.expert_review_packet.reviewed_by_professional,false);
 assert.equal(m.specialty_test.independent_human_signoff,false);
 assert.equal(m.specialty_test.human_experts_participated,0);
 assert.equal(m.specialty_test.specialist_perspective,t.reviewer_profile);
 const orig=old.material.construction?.roleplay??old.material.learning;
 const now=m.construction?.roleplay??m.learning;
 assert.deepEqual(now,orig,'Original quiz content and answer key changed '+key);
 assert.equal(t.previous_quiz.correct_text,now.options[now.correct]);
 const s=m.sections;
 assert.equal(s.at(-4).heading,'Doprecyzowanie praktyczne','Old revision must survive');
 assert.equal(s.at(-3).heading,'Ćwiczenie diagnostyczne z kryterium odbioru','Old exercise must survive');
 assert.equal(s.at(-2).heading,'Próba zawodowa — trudniejszy przypadek');
 assert.equal(s.at(-1).heading,'Sprawdź wynik po wykonaniu');
 assert(s.at(-2).text.includes(t.advanced_case)&&s.at(-1).text.includes(t.expected_resolution));
 assert(s.at(-1).text.includes(t.required_fix),'Missing corrective nuance '+key);
 assert(m.lesson_tips?.length>=4,'The fourth specialty-specific tip must appear '+key);
 assert.equal(m.specialty_test.original_correct_index,now.correct);
 assert(m.illustration,'Illustration unexpectedly missing '+key);
}
assert.equal(Math.ceil(25/.8),32);
assert.equal(24/.8,30);
assert.equal(4*7-4,24);
assert.equal(5*550,2750);
assert.equal(36/40,0.9);
assert.equal(28/40,0.7);
assert.equal(15/.75,20);
assert.equal(35_000+1800+1200,38_000);
console.log('✓ 64 advanced specialist-like cases, 64 remedies and 64 additional tips; all original quizzes and pending human signoffs preserved');
